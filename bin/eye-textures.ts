// Renders the eye SVGs (assets/tonio/eyes/) to the PNGs the export embeds,
// written as base64 into src/upstream/eyes/textures.ts. A build step run by
// hand after an SVG changes: the export itself has no SVG renderer, so it
// recolours these PNGs instead (src/upstream/eyes/recolour.ts).
//
//   bun bin/eye-textures.ts        (needs `bunx playwright-core install chromium`)

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { chromium } from 'playwright-core'

const ROOT = join(import.meta.dir, '..')
const STYLES = ['basic', 'anime'] as const
const SIZE = 256

const browser = await chromium.launch()
const page = await browser.newPage({
  viewport: { width: SIZE, height: SIZE },
  deviceScaleFactor: 1,
})
const out: Record<string, string> = {}
for (const style of STYLES) {
  const svg = readFileSync(
    join(ROOT, 'assets/tonio/eyes', `${style}-eye.svg`),
    'utf8'
  )
  await page.setContent(
    `<html><body style="margin:0"><img src="data:image/svg+xml;base64,${Buffer.from(
      svg
    ).toString(
      'base64'
    )}" width="${SIZE}" height="${SIZE}" style="display:block"></body></html>`
  )
  await page.waitForFunction(() => document.images[0]?.complete)
  const png = await page.screenshot({
    clip: { x: 0, y: 0, width: SIZE, height: SIZE },
  })
  out[style] = png.toString('base64')
  console.log(`${style}: ${png.byteLength} bytes`)
}
await browser.close()

writeFileSync(
  join(ROOT, 'src/upstream/eyes/textures.ts'),
  `// GENERATED by bin/eye-textures.ts from assets/tonio/eyes/*.svg (Tonio
// Loewald, CC0). Do not edit: change the SVG and run the script.

/** The eye styles, as \`eyeStyle\` names them. */
export const EYE_STYLES = ${JSON.stringify(STYLES)} as const
export type EyeStyle = (typeof EYE_STYLES)[number]

/** Each style's PNG (${SIZE} × ${SIZE}), base64. */
export const EYE_PNG: Readonly<Record<EyeStyle, string>> = Object.freeze({
${STYLES.map((s) => `  ${s}: '${out[s]}',`).join('\n')}
})
`
)
