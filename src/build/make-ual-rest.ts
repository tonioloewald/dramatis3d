// Writes src/build/ual-rest.ts: UAL's rest pose (each joint's local
// translation and rotation, in UE_JOINTS order) read from a UAL GLB. The
// default source is the gate-1 clip fixture, which carries UAL1.glb's
// armature unchanged (Quaternius, Universal Animation Library, CC0 1.0).
//
//   bun src/build/make-ual-rest.ts [path to a UAL GLB]
//
// ual-rest.test.ts checks the written table against the fixture.

import { UE_JOINTS } from '../contracts/profile'
import { readGlb } from 'tosijs-3d/glb-chunks'

const source =
  process.argv[2] ??
  new URL('../../test/gate1/fixtures/ual-walk.glb', import.meta.url).pathname
const glb = readGlb(new Uint8Array(await Bun.file(source).arrayBuffer()))
type Node = { name?: string; translation?: number[]; rotation?: number[] }
const byName = new Map<string, Node>(
  (glb.json.nodes as Node[]).flatMap((n) =>
    n.name === undefined ? [] : [[n.name, n]]
  )
)
const round = (v: number): number => Number(v.toPrecision(9))
const rows = UE_JOINTS.map(({ name }) => {
  const n = byName.get(name)
  if (n === undefined) throw new Error(`${source} has no joint ${name}`)
  const t = (n.translation ?? [0, 0, 0]).map(round)
  const r = (n.rotation ?? [0, 0, 0, 1]).map(round)
  return `  [${JSON.stringify(name)}, [${t.join(', ')}], [${r.join(', ')}]],`
})
const text = `// GENERATED by src/build/make-ual-rest.ts from UAL's armature (Quaternius,
// Universal Animation Library, CC0 1.0, https://quaternius.com). Do not edit.
//
// UAL's rest pose: each joint's local translation (metres) and rotation
// (x, y, z, w) relative to its parent, in UE_JOINTS order. The export's
// joint frames are these rotations (export-format.md, "Rest pose").

export const UAL_REST: ReadonlyArray<
  readonly [string, readonly [number, number, number], readonly [number, number, number, number]]
> = [
${rows.join('\n')}
]
`
const target = new URL('./ual-rest.ts', import.meta.url).pathname
await Bun.write(target, text)
console.log(`wrote ${target}: ${rows.length} joints`)
